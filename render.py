RENDERERS = (ghostty, zellij, fish, starship, delta, k9s, gh_dash)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("palette", nargs="*", help="palette slugs to render (default: all)")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = parser.parse_args()

    sources = sorted(PALETTES.glob("*.yaml"))
    if args.palette:
        wanted = set(args.palette)
        sources = [s for s in sources if s.stem in wanted]
        unknown = wanted - {s.stem for s in sources}
        if unknown:
            print(f"no such palette: {', '.join(sorted(unknown))}", file=sys.stderr)
            return 2
    if not sources:
        print(f"no palettes found in {PALETTES}", file=sys.stderr)
        return 2

    failed = False
    for source in sources:
        try:
            palette = load(source)
        except PaletteError as exc:
            print(f"✘ {source.stem}: {exc}", file=sys.stderr)
            failed = True
            continue

        problems = audit(palette)
        ratio = contrast(palette.text, palette.ground)

        if problems and palette.reference:
            print(f"– {palette.slug}  reference palette, not rendered")
            for problem in problems:
                print(f"    {problem}")
            continue
        if problems:
            failed = True
            print(f"✘ {palette.slug}  text {ratio:.1f}:1")
            for problem in problems:
                print(f"    {problem}")
            continue

        print(f"✔ {palette.slug}  text {ratio:.1f}:1", end="")
        if args.check:
            print()
            continue

        for renderer in RENDERERS:
            rel, content = renderer(palette)
            target = OUT / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        print(f"  →  {len(RENDERERS)} tool files")

    if failed:
        print("\nSome palettes were rejected; nothing was written for those.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
