"""Render one palette source into a theme file for every tool that takes one.

A palette under palettes/ is the single source of truth. One folder per tool at
the repository root is generated, so edit the YAML and re-run; never edit those
folders by hand.

    uv run render.py            # render every palette
    uv run render.py --check    # validate only, write nothing
    uv run render.py fmind      # render one palette

The readability contract lives in palette.py, and a palette that misses it is
refused rather than rendered, so the run exits non-zero instead of shipping a
terminal that cannot be read.
"""

