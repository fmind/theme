def ghostty(p: Palette) -> tuple[str, str]:
    lines = [
        f"# {p.name} — generated by render.py, do not edit",
        f"# source: palettes/{p.source.name}",
        "",
        f"background = {p.ground}",
        f"foreground = {p.text}",
        f"cursor-color = {p.cursor}",
        f"selection-background = {p.surface('selection')}",
        f"selection-foreground = {p.ansi['bright_white']}",
    ]
    lines += [f"palette = {i}={p.slot(i)}" for i in range(16)]

    # Slots 16-255 are the xterm cube, and a theme that stops at 15 leaves every
    # tool that reaches into it looking untouched. The 6x6x6 cube (16-231) is
    # left alone - tools compute gradients from its structure - but the 24-step
    # greyscale ramp (232-255) is only ever used for "grey", so it is reissued at
    # the same luminance with the theme's own cast. That is what makes lsd's
    # `243` and a dozen other tools pick the theme up for free.
    lines += ["", "# greyscale ramp, at xterm luminance with the theme's cast"]
    lines += [
        f"palette = {232 + i}={oklch_hex(lightness(grey), 0.010, hue(p.role('comment')))}"
        for i, grey in enumerate(f"#{v:02x}{v:02x}{v:02x}" for v in range(8, 239, 10))
    ]
    return f"ghostty/{p.slug}", "\n".join(lines) + "\n"


def zellij(p: Palette) -> tuple[str, str]:
    """The full styling block, not the classic ten colours.

    Handed the ten-colour form, Zellij *derives* its whole UI from it - and the
    two things it derives backgrounds from are `fg` and `green`. In this palette
    that means every unselected tab is a solid block of body green and the
    selected tab and mode chip are solid blocks of the near-white `string`: the
    two brightest colours in the palette, painted as fills, across the top and
    bottom of the screen for the whole session. Nothing on the palette side can
    stop it, because the palette does not get to say where those slots land.

    The named form does. Chrome is chrome: ribbons, lists and table cells sit on
    the same second grounds every other tool uses, `punctuation` carries the text
    you do not read, and the body green is spent on the one ribbon that says
    where you are. The active tab reads as bright green text on a dark chip
    rather than as a lit block, which is both the quieter thing and the more
    phosphor-looking one.

    `frame_unselected` is emitted rather than left out. Zellij falls back to
    `frame_selected` for both, so an unfocused pane is framed exactly like the
    focused one and the frame stops answering the only question it is there for.
    """
    r = {role: p.role(role) for role in ROLES}
    panel, selection = p.surface("panel"), p.surface("selection")

    # One emphasis quartet for everything that is read rather than filled. Zellij
    # spends these on keybinding hints, so they are the four accents that stay
    # legible small: warm first, then the three cool tiers.
    accents = (r["number"], r["type"], r["escape"], r["property"])

    def block(name: str, base: str, background: str | None, emphasis=accents) -> str:
        rows = [f'            base "{base}"']
        if background is not None:
            rows.append(f'            background "{background}"')
        rows += [f'            emphasis_{i} "{c}"' for i, c in enumerate(emphasis)]
        return f"        {name} {{\n" + "\n".join(rows) + "\n        }"

    players = ("keyword", "function", "builtin", "number", "type",
               "constant", "error", "punctuation", "warning", "property")
    multiplayer = "        multiplayer_user_colors {\n" + "\n".join(
        f'            player_{i + 1} "{r[role]}"' for i, role in enumerate(players)
    ) + "\n        }"

    blocks = [
        # the status bar and anything else that is plain text
        block("text_unselected", r["punctuation"], p.ground),
        block("text_selected", p.text, selection),
        # tabs and mode chips: the selected one is the only lit thing up there
        block("ribbon_unselected", r["comment"], panel),
        block("ribbon_selected", p.text, selection),
        # pane frames: focused is green, unfocused recedes, highlight is the
        # orange Zellij already uses for renaming and searching
        block("frame_unselected", r["comment"], None),
        block("frame_selected", r["function"], None),
        block("frame_highlight", r["number"], None),
        # plugin tables and lists
        block("table_title", r["escape"], panel),
        block("table_cell_unselected", r["punctuation"], p.ground),
        block("table_cell_selected", p.text, selection),
        block("list_unselected", r["punctuation"], p.ground),
        block("list_selected", p.text, selection),
        # a command that worked, and one that did not
        block("exit_code_success", r["function"], None),
        block("exit_code_error", r["error"], None),
        multiplayer,
    ]
    return f"zellij/{p.slug}.kdl", (
        f"// {p.name} — generated by render.py, do not edit\n"
        f"// source: palettes/{p.source.name}\n"
        "//\n"
        "// Named styles, not the ten-colour palette form: Zellij derives ribbon\n"
        "// backgrounds from `fg` and `green` in that form, which paints the tab bar\n"
        "// in the two brightest colours the palette has.\n\n"
        "themes {\n"
        f"    {p.slug} {{\n"
        + "\n".join(blocks)
        + "\n    }\n}\n"
    )


def fish(p: Palette) -> tuple[str, str]:
    """fish names its own roles, so this is where the mapping is explicit.

    It is also the clearest demonstration of the fifteen-role palette: a command,
    its arguments and its flags are three different colours rather than one,
    because they are three different things.

    Bold does the work hue cannot. FiraCode ships a real Bold face and no italic
    at all, so bold is the only attribute axis available - spent on the roles you
    scan for (commands, keywords, errors) rather than the ones you read through.
    """
    a = p.ansi
    pairs = [
        ("normal", p.text, "variable"),
        ("command", a["blue"], "function"),
        ("param", a["bright_blue"], "parameter"),
        ("option", a["bright_magenta"], "builtin"),
        ("keyword", a["magenta"], "keyword"),
        ("quote", a["green"], "string"),
        ("escape", a["bright_green"], "escape"),
        ("redirection", a["cyan"], "type"),
        ("operator", a["bright_cyan"], "property"),
        ("end", a["bright_yellow"], "constant"),
        ("error", a["red"], "error"),
        ("comment", a["bright_black"], "comment"),
        ("autosuggestion", a["bright_black"], "comment"),
        ("cancel", a["bright_red"], "warning"),
        ("cwd", p.text, "variable"),
        ("cwd_root", a["red"], "error"),
        ("user", a["bright_cyan"], "property"),
        ("host", a["cyan"], "type"),
        ("host_remote", a["yellow"], "number"),
    ]
    selection = p.surface("selection").lstrip("#")
    lines = [
        f"# {p.name} — generated by render.py, do not edit",
        f"# source: palettes/{p.source.name}",
        "",
        "# Syntax highlighting and prompt identity",
    ]
    lines += [
        f"set -g fish_color_{key} {value.lstrip('#')}"
        + (" --bold" if role in BOLD_ROLES else "")
        + f"  # {role}"
        for key, value, role in pairs
    ]
    lines += [
        f"set -g fish_color_selection --background={selection}",
        f"set -g fish_color_search_match --background={selection}",
        "set -g fish_color_valid_path --underline",
        "",
        "# Completion pager",
        f"set -g fish_pager_color_progress {a['bright_black'].lstrip('#')}",
        f"set -g fish_pager_color_prefix {a['cyan'].lstrip('#')} --bold",
        f"set -g fish_pager_color_completion {p.text.lstrip('#')}",
        f"set -g fish_pager_color_description {a['bright_black'].lstrip('#')}",
        f"set -g fish_pager_color_selected_background --background={selection}",
    ]
    return f"fish/{p.slug}.fish", "\n".join(lines) + "\n"


