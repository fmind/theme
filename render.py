CELL, LEAD, PAD = 8.4, 22.0, 18.0


def _svg(p: Palette, sample: list[list[tuple[str, str]]], title: str) -> str:
    width = PAD * 2 + CELL * max((sum(len(t) for _, t in line) for line in sample), default=0)
    height = PAD * 2 + LEAD * len(sample)
    rows = []
    for i, line in enumerate(sample):
        spans = "".join(
            f'<tspan fill="{p.role(role)}"'
            + (' font-weight="bold"' if role in BOLD_ROLES else "")
            + f">{text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')}</tspan>"
            for role, text in line
        )
        rows.append(
            f'<text xml:space="preserve" x="{PAD}" y="{PAD + LEAD * i + 15:.1f}">{spans}</text>'
        )
    body = "\n    ".join(rows)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0f}" height="{height:.0f}" '
        f'viewBox="0 0 {width:.0f} {height:.0f}" role="img" aria-label="{title}">\n'
        f'  <rect width="100%" height="100%" fill="{p.ground}"/>\n'
        f'  <g font-family="FiraCode Nerd Font Mono, Fira Code, DejaVu Sans Mono, monospace" '
        f'font-size="14" font-feature-settings="&apos;liga&apos; 0, &apos;calt&apos; 0">'
        f'\n    {body}\n  </g>\n</svg>\n'
    )


def preview_code(p: Palette) -> tuple[str, str]:
    return f"preview/{p.slug}-code.svg", _svg(p, CODE_SAMPLE, f"{p.name} syntax preview")


def preview_shell(p: Palette) -> tuple[str, str]:
    return f"preview/{p.slug}-shell.svg", _svg(p, SHELL_SAMPLE, f"{p.name} shell preview")


def preview_palette(p: Palette) -> tuple[str, str]:
    """The fifteen roles as labelled swatches."""
    rows = [(r, p.role(r), SLOT_LABEL[r]) for r in ROLES]
    w, h, pad = 560.0, 26.0, 16.0
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:.0f}" '
        f'height="{pad * 2 + h * len(rows):.0f}" role="img" aria-label="{p.name} roles">',
        f'  <rect width="100%" height="100%" fill="{p.ground}"/>',
        '  <g font-family="FiraCode Nerd Font Mono, Fira Code, DejaVu Sans Mono, monospace" '
        'font-size="13">',
    ]
    for i, (role, colour, slot) in enumerate(rows):
        y = pad + h * i
        out += [
            f'    <rect x="{pad}" y="{y + 4:.0f}" width="70" height="17" rx="2" fill="{colour}"/>',
            f'    <text x="{pad + 82}" y="{y + 17:.0f}" fill="{p.text}">{role}</text>',
            f'    <text x="{pad + 230}" y="{y + 17:.0f}" fill="{p.role("punctuation")}">{colour}</text>',
            f'    <text x="{pad + 340}" y="{y + 17:.0f}" fill="{p.role("comment")}">{slot}</text>',
        ]
    out += ["  </g>", "</svg>", ""]
    return f"preview/{p.slug}-roles.svg", "\n".join(out)


