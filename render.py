def delta(p: Palette) -> tuple[str, str]:
    """Diff grounds are the palette's own red and green pulled onto the ground."""
    a = p.ansi
    return f"delta/{p.slug}.gitconfig", (
        f"# {p.name} — generated by render.py, do not edit\n"
        f"# source: palettes/{p.source.name}\n"
        "# Include from ~/.gitconfig, or paste into its [delta] section.\n\n"
        "[delta]\n"
        '    syntax-theme = "ansi"\n'
        f'    minus-style = syntax "{mix(p.ground, a["red"], 0.20)}"\n'
        f'    minus-emph-style = syntax "{mix(p.ground, a["red"], 0.38)}"\n'
        f'    plus-style = syntax "{mix(p.ground, a["green"], 0.18)}"\n'
        f'    plus-emph-style = syntax "{mix(p.ground, a["green"], 0.34)}"\n'
        f'    hunk-header-style = "{a["bright_black"]}"\n'
        f'    file-style = "{a["bright_green"]}"\n'
        f'    line-numbers-zero-style = "{a["bright_black"]}"\n'
    )


