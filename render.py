def preview_palette(p: Palette) -> tuple[str, str]:
    """The fifteen roles as labelled swatches."""
    rows = [(r, p.role(r), SLOT_LABEL[r]) for r in ROLES]
    w, h, pad = 560.0, 26.0, 16.0
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:.0f}" '
        f'height="{pad * 2 + h * len(rows):.0f}" role="img" aria-label="{p.name} roles">',
        f'  <rect width="100%" height="100%" fill="{p.ground}"/>',
        '  <g font-family="FiraCode Nerd Font Mono, Fira Code, DejaVu Sans Mono, monospace" '
        'font-size="13">',
    ]
    for i, (role, colour, slot) in enumerate(rows):
        y = pad + h * i
        out += [
            f'    <rect x="{pad}" y="{y + 4:.0f}" width="70" height="17" rx="2" fill="{colour}"/>',
            f'    <text x="{pad + 82}" y="{y + 17:.0f}" fill="{p.text}">{role}</text>',
            f'    <text x="{pad + 230}" y="{y + 17:.0f}" fill="{p.role("punctuation")}">{colour}</text>',
            f'    <text x="{pad + 340}" y="{y + 17:.0f}" fill="{p.role("comment")}">{slot}</text>',
        ]
    out += ["  </g>", "</svg>", ""]
