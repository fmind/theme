"""Render one palette source into a theme file for every tool that takes one.

A palette under palettes/ is the single source of truth. Everything in out/ is
generated, so edit the YAML and re-run; never edit out/ by hand.

    uv run render.py            # render every palette
    uv run render.py --check    # validate only, write nothing
    uv run render.py fmind      # render one palette

The readability contract lives in palette.py and is shared with explore.py, so
what gets designed and what gets shipped cannot drift apart. A palette that
misses it is refused and the run exits non-zero.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from palette import BOLD_ROLES, Palette, PaletteError, audit, contrast, load, mix

ROOT = Path(__file__).parent
PALETTES = ROOT / "palettes"
OUT = ROOT / "out"


# ------------------------------------------------------------------- renderers
# Each takes a Palette and returns (path relative to out/, file contents).
# Adding a tool means adding one function here and one entry in RENDERERS.


def ghostty(p: Palette) -> tuple[str, str]:
    lines = [
        f"# {p.name} — generated by render.py, do not edit",
        f"# source: palettes/{p.source.name}",
        "",
        f"background = {p.ground}",
        f"foreground = {p.text}",
        f"cursor-color = {p.cursor}",
        f"selection-background = {mix(p.ground, p.ansi['green'], 0.22)}",
        f"selection-foreground = {p.ansi['bright_white']}",
    ]
    lines += [f"palette = {i}={p.slot(i)}" for i in range(16)]
    return f"ghostty/{p.slug}", "\n".join(lines) + "\n"


def zellij(p: Palette) -> tuple[str, str]:
    body = "\n".join(
        f'        {key} "{p.ansi[key]}"'
        for key in ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
    )
    return f"zellij/{p.slug}.kdl", (
        f"// {p.name} — generated by render.py, do not edit\n"
        f"// source: palettes/{p.source.name}\n\n"
        "themes {\n"
        f"    {p.slug} {{\n"
        f'        fg "{p.text}"\n'
        f'        bg "{p.ground}"\n'
        f"{body}\n"
        f'        orange "{p.ansi["yellow"]}"\n'
        "    }\n"
        "}\n"
    )


def fish(p: Palette) -> tuple[str, str]:
    """fish names its own roles, so this is where the mapping is explicit.

    It is also the clearest demonstration of the fourteen-role palette: a
    command, its arguments and its flags are three different greens rather than
    one, because they are three different things.

    Bold does the work hue cannot. FiraCode ships a real Bold face and no italic
    at all, so bold is the only attribute axis available - spent on the roles you
    scan for (commands, keywords, errors) rather than the ones you read through.
    """
    a = p.ansi
    pairs = [
        ("normal", p.text, "variable"),
        ("command", a["blue"], "function"),
        ("param", a["bright_blue"], "parameter"),
        ("option", a["bright_magenta"], "builtin"),
        ("keyword", a["magenta"], "keyword"),
        ("quote", a["green"], "string"),
        ("escape", a["bright_green"], "escape"),
        ("redirection", a["cyan"], "type"),
        ("operator", a["bright_cyan"], "property"),
        ("end", a["bright_yellow"], "constant"),
        ("error", a["red"], "error"),
        ("comment", a["bright_black"], "comment"),
        ("autosuggestion", a["bright_black"], "comment"),
        ("cancel", a["bright_red"], "warning"),
        ("cwd", p.text, "variable"),
        ("cwd_root", a["red"], "error"),
        ("user", a["bright_cyan"], "property"),
        ("host", a["cyan"], "type"),
        ("host_remote", a["yellow"], "number"),
    ]
    selection = mix(p.ground, a["green"], 0.22).lstrip("#")
    lines = [
        f"# {p.name} — generated by render.py, do not edit",
        f"# source: palettes/{p.source.name}",
        "",
        "# Syntax highlighting and prompt identity",
    ]
    lines += [
        f"set -g fish_color_{key} {value.lstrip('#')}"
        + (" --bold" if role in BOLD_ROLES else "")
        + f"  # {role}"
        for key, value, role in pairs
    ]
    lines += [
        f"set -g fish_color_selection --background={selection}",
        f"set -g fish_color_search_match --background={selection}",
        "set -g fish_color_valid_path --underline",
        "",
        "# Completion pager",
        f"set -g fish_pager_color_progress {a['bright_black'].lstrip('#')}",
        f"set -g fish_pager_color_prefix {a['cyan'].lstrip('#')} --bold",
        f"set -g fish_pager_color_completion {p.text.lstrip('#')}",
        f"set -g fish_pager_color_description {a['bright_black'].lstrip('#')}",
        f"set -g fish_pager_color_selected_background --background={selection}",
    ]
    return f"fish/{p.slug}.fish", "\n".join(lines) + "\n"


