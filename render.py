# Every tool that takes a palette, and then the README images. Kept apart so
# the run reports how many tools were themed rather than counting pictures.
TOOLS = (ghostty, zellij, fish, fzf, starship, delta, k9s, gh_dash, opencode,
         lualine,
         ptpython, neovim)
PREVIEWS = (preview_code, preview_shell, preview_palette)
RENDERERS = TOOLS + PREVIEWS


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("palette", nargs="*", help="palette slugs to render (default: all)")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = parser.parse_args()

    sources = sorted(PALETTES.glob("*.yaml"))
    if args.palette:
        wanted = set(args.palette)
        sources = [s for s in sources if s.stem in wanted]
        unknown = wanted - {s.stem for s in sources}
        if unknown:
            print(f"no such palette: {', '.join(sorted(unknown))}", file=sys.stderr)
            return 2
    if not sources:
        print(f"no palettes found in {PALETTES}", file=sys.stderr)
        return 2

    failed = False
    for source in sources:
        try:
            palette = load(source)
        except PaletteError as exc:
            print(f"✘ {source.stem}: {exc}", file=sys.stderr)
            failed = True
            continue

        problems = audit(palette)
        if problems:
            failed = True
            print(f"✘ {palette.slug}")
            for problem in problems:
                print(f"    {problem}")
            continue

        m = measure(palette)
        print(f"✔ {palette.slug}  text {m['text_contrast']}:1  "
              f"{m['hue_families']} hue families  {m['green_share']}% green  "
              f"separation {m['min_separation']} ({m['tightest_pair']}, "
              f"{m['slack']:+.3f})", end="")
        if args.check:
            print()
            continue

        for renderer in RENDERERS:
            rel, content = renderer(palette)
            target = OUT / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        print(f"  →  {len(TOOLS)} tools, {len(PREVIEWS)} previews")

    if failed:
        print("\nSome palettes were rejected; nothing was written for those.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
