def fzf(p: Palette) -> tuple[str, str]:
    """The one tool that is handed slot numbers instead of colours.

    Everything else here paints its own window and gets the palette's hex. fzf
    draws over whatever is already on the screen, so hex would pin the finder to
    one palette while the terminal around it followed Ghostty. `-1` leaves the
    ground, the body text and the gutter exactly as the terminal has them, and
    the slot numbers put every accent on the same sixteen colours as the shell
    it is covering.

    Read through $FZF_DEFAULT_OPTS_FILE, which is evaluated before
    $FZF_DEFAULT_OPTS, so the shell keeps owning layout and key bindings.
    """
    n = {role: ANSI.index(SLOT_OF[role]) for role in ROLES if SLOT_OF[role] != "text"}
    black = ANSI.index("black")
    groups: list[tuple[str, list[tuple[str, object, str]]]] = [
        ("ground and body, left to the terminal", [
            ("fg", -1, "the terminal's own foreground"),
            ("bg", -1, "transparent over the prompt"),
            ("gutter", -1, "no bar down the left"),
            ("query", -1, "what you typed reads as input"),
        ]),
        ("the current line", [
            ("fg+", -1, "body colour, not an accent"),
            ("bg+", black, "slot 0, the palette's own dark"),
            ("hl", n["escape"], "escape — the matched run"),
            ("hl+", n["escape"], "escape — matched, on the current line"),
        ]),
        ("chrome recedes, the way comments do", [
            ("border", n["comment"], "comment"),
            ("separator", n["comment"], "comment"),
            ("scrollbar", n["comment"], "comment"),
            ("info", n["comment"], "comment"),
            ("disabled", n["comment"], "comment"),
        ]),
        ("what you point at and what you pick", [
            ("prompt", n["keyword"], "keyword"),
            ("pointer", n["constant"], "constant"),
            ("marker", n["parameter"], "parameter"),
            ("spinner", n["property"], "property"),
            ("header", n["type"], "type"),
            ("label", n["type"], "type"),
        ]),
    ]
    width = max(len(f"--color={key}:{value}") for _, entries in groups for key, value, _ in entries)
    lines = [
        f"# {p.name} — generated by render.py, do not edit",
        f"# source: palettes/{p.source.name}",
        "#",
        "# Point fzf at this file with FZF_DEFAULT_OPTS_FILE. Colours are ANSI slot",
        "# numbers so the finder follows the terminal; -1 means 'leave it alone'.",
        "",
        "# base16 first: everything not named below falls back to a palette slot",
        "# rather than to one of fzf's own 256-colour defaults.",
        "--color=base16",
    ]
    for note, entries in groups:
        lines += ["", f"# {note}"]
        lines += [
            f"--color={key}:{value}".ljust(width) + f"  # {why}"
            for key, value, why in entries
        ]
    return f"fzf/{p.slug}.conf", "\n".join(lines) + "\n"


def opencode(p: Palette) -> tuple[str, str]:
    """opencode ships its own palette, so it needs the whole theme, not a hint.

    It is a JSON theme dropped into themes/, selected by name. The syntax half
    maps role for role; the chrome half is built from the same mixes the diff
    backgrounds use, so a panel is the ground with a little green in it rather
    than a grey borrowed from somewhere else.
    """
    defs = {role: p.role(role) for role in ROLES}
    defs |= {
        "ground": p.ground,
        "panel": p.surface("panel"),
        "element": p.surface("selection"),
        "addedBg": p.surface("plus_emph"),
        "removedBg": p.surface("minus_emph"),
        "addedGutter": p.surface("plus"),
        "removedGutter": p.surface("minus"),
    }
    theme = {
        "primary": "escape",
        "secondary": "type",
        "accent": "keyword",
        "error": "error",
        "warning": "warning",
        # `success` and `diffAdded` used to point at `string`, which is a white
        # here: opencode's own version of the slot-2 trap. SEMANTIC names them.
        "success": SEMANTIC["ok"],
        "info": "type",
        "text": "variable",
        "textMuted": "comment",
        "background": "ground",
        "backgroundPanel": "panel",
        "backgroundElement": "element",
        "border": "comment",
        "borderActive": "escape",
        "borderSubtle": "element",
        "diffAdded": SEMANTIC["added"],
        "diffRemoved": "error",
        "diffContext": "comment",
        "diffHunkHeader": "comment",
        "diffHighlightAdded": "escape",
        "diffHighlightRemoved": "warning",
        "diffAddedBg": "addedBg",
        "diffRemovedBg": "removedBg",
        "diffContextBg": "panel",
        "diffLineNumber": "comment",
        "diffAddedLineNumberBg": "addedGutter",
        "diffRemovedLineNumberBg": "removedGutter",
        # Markdown is the same filetype in both tools, so it is painted the same
        # way as the colorscheme paints it: a heading at level one, inline code in
        # `escape`, chalk on the bullets and the rules. It used to disagree on all
        # three - a white inline code, violet bullets, an amber strong - which
        # makes a document look like a different document depending on which
        # window it is in.
        "markdownText": "variable",
        "markdownHeading": HEADING_LADDER[0],
        "markdownLink": "parameter",
        "markdownLinkText": "parameter",
        "markdownCode": "escape",
        "markdownCodeBlock": "variable",
        "markdownBlockQuote": "punctuation",
        "markdownEmph": "property",
        "markdownStrong": "variable",
        "markdownHorizontalRule": "comment",
        "markdownListItem": "punctuation",
        "markdownListEnumeration": "punctuation",
        "markdownImage": "builtin",
        "markdownImageText": "property",
        "syntaxComment": "comment",
        "syntaxKeyword": "keyword",
        "syntaxFunction": "function",
        "syntaxVariable": "variable",
        "syntaxString": "string",
        "syntaxNumber": "number",
        "syntaxType": "type",
        "syntaxOperator": "punctuation",
        "syntaxPunctuation": "punctuation",
    }
    document = {
        "$schema": "https://opencode.ai/theme.json",
        "_generated": f"{p.name} — render.py, do not edit; source palettes/{p.source.name}",
        "defs": defs,
        "theme": theme,
    }
    return f"opencode/{p.slug}.json", json.dumps(document, indent=2) + "\n"


